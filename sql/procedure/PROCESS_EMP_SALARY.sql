CREATE OR REPLACE PROCEDURE PROCESS_EMP_SALARY
AS 
TYPE T_REC IS RECORD(EMP_ID EMP_SALARY_STAGE.EMP_ID%TYPE,NEW_SALARY EMP_SALARY_STAGE.NEW_SALARY%TYPE);
TYPE T_EMP IS TABLE OF T_REC;
V_EMP T_EMP;
V_EXCEP EXCEPTION;
PRAGMA EXCEPTION_INIT(V_EXCEP, -24381);
V_ERROR_CODE NUMBER;
V_ERROR_MESSAGE VARCHAR2(4000);
V_EMP_ID EMP_SALARY_STAGE.EMP_ID%TYPE;
TYPE T_CUR IS REF CURSOR;
C_EMP T_CUR;
BEGIN 

	OPEN C_EMP FOR SELECT EMP_ID,NEW_SALARY FROM EMP_SALARY_STAGE;
		LOOP 
			FETCH C_EMP BULK COLLECT INTO V_EMP LIMIT 1000;
				EXIT WHEN V_EMP.COUNT =0;
			BEGIN 
			
				FORALL I IN 1..V_EMP.COUNT SAVE EXCEPTIONS
				
					UPDATE EMPLOYEE SET SALARY = V_EMP(I).NEW_SALARY WHERE EMP_ID = V_EMP(I).EMP_ID;
				
			EXCEPTION 
			
			WHEN V_EXCEP THEN 
				FOR I IN 1..SQL%BULK_EXCEPTIONS.COUNT
				LOOP 
					V_ERROR_CODE := SQL%BULK_EXCEPTIONS(I).ERROR_CODE;
					V_ERROR_MESSAGE := SQLERRM(-V_ERROR_CODE);
					V_EMP_ID := V_EMP(SQL%BULK_EXCEPTIONS(I).ERROR_INDEX).EMP_ID;
					
					INSERT INTO EMP_UPDATE_ERROR_LOG (	EMP_ID,
														ERROR_CODE,
														ERROR_MESSAGE,
														LOG_DATE) VALUES (V_EMP_ID,-V_ERROR_CODE,V_ERROR_MESSAGE,SYSDATE);
														
				END LOOP;
			END;
		END LOOP;
	CLOSE C_EMP;	
	
	COMMIT;
	
EXCEPTION 

	WHEN OTHERS THEN 
		IF C_EMP%ISOPEN THEN
			CLOSE C_EMP;
		END IF;
		DBMS_OUTPUT.PUT_LINE('UNEXPECTED ERROR ' || SQLERRM);
		ROLLBACK;
		RAISE;
END;
/

			